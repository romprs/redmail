def components() -> list[list[str]]:
    path = Path(__file__).resolve().parent / "components.txt"
    rows: list[list[str]] = []
    if not path.exists():
        return rows
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        name, version, license_, homepage = (line.split("|") + ["", "", "", ""])[:4]
        rows.append([name, version, license_, homepage])
    return rows


