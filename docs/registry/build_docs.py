LISTING_FILES = [
    "src/redmail/__main__.py",
    "src/redmail/imap_client.py",
    "src/redmail/mailbox.py",
    "src/redmail/smtp_client.py",
    "src/redmail/itip.py",
    "src/redmail/caldav_sync.py",
    "src/redmail/archive_store.py",
    "src/redmail/calendar_store.py",
    "src/redmail/gssapi_sasl.py",
]
LISTING_MAX_LINES = 2600  # ≈ 60–65 страниц (длинные строки переносятся)


def doc_listing() -> Path:
    doc = Document()
    section = doc.sections[0]
    section.left_margin = Cm(2)
    section.right_margin = Cm(1.5)
    section.top_margin = Cm(1.5)
    section.bottom_margin = Cm(1.5)
    style = doc.styles["Normal"]
    style.font.name = "Courier New"
    style.font.size = Pt(7)
    style.element.rPr.rFonts.set(qn("w:eastAsia"), "Courier New")
    style.paragraph_format.space_after = Pt(0)
    style.paragraph_format.line_spacing = 1.0
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(f"Программа для ЭВМ «{PRODUCT_NAME}». Листинг исходного кода (фрагменты). "
                  f"Правообладатель: {RIGHTSHOLDER}, {YEAR}. Язык: Python 3.")
    r.bold = True
    doc.add_paragraph()
    budget = LISTING_MAX_LINES
    for rel in LISTING_FILES:
        if budget <= 0:
            break
        path = ROOT / rel
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        take = lines[:budget]
        budget -= len(take)
        head = doc.add_paragraph()
        hr = head.add_run(f"===== {rel} ({len(lines)} строк{'' if len(take) == len(lines) else ', показаны первые ' + str(len(take))}) =====")
        hr.bold = True
        for i, line in enumerate(take, 1):
            para_ = doc.add_paragraph()
            para_.add_run(f"{i:5d}  {line.rstrip()}" if line.strip() else " ")
        doc.add_paragraph()
    return save(doc, "08_Листинг_исходного_кода.docx")


